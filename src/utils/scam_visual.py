def near_copy(im):
    ratio, h, v, a = fingerprint(im)
    return any(abs(ratio-r) <= r*0.02 and (h^hh).bit_count() <= 32
               and (v^vv).bit_count() <= 24 and (a^aa).bit_count() <= 8
               for r,hh,vv,aa in REFERENCES)
