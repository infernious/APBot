"""Conservative near-copy fingerprints for the supplied campaign images.
Only use after decoding a supported still image in the isolated worker.
"""
from PIL import Image


def fingerprint(im):
    grey = im.convert('L')
    def bits(values):
        result = 0
        for v in values:
            result = (result << 1) | int(v)
        return result
    h = grey.resize((17, 16), Image.Resampling.LANCZOS).tobytes()
    v = grey.resize((16, 17), Image.Resampling.LANCZOS).tobytes()
    a = grey.resize((16, 16), Image.Resampling.LANCZOS).tobytes()
    mean = sum(a) / len(a)
    return (round(im.width / im.height * 10000),
            bits(h[y*17+x] > h[y*17+x+1] for y in range(16) for x in range(16)),
            bits(v[y*16+x] > v[(y+1)*16+x] for y in range(16) for x in range(16)),
            bits(x > mean for x in a))


